static void Sci_Config(volatile struct SCI_REGS *sci)
{
    // FIFO on, both FIFOs out of reset. 0xE040 / 0x2044 match the
    // proven C2000Ware SCI FIFO loopback init (SCIRST, SCIFFENA,
    // TXFIFORESET, RXFIFORESET, interrupt flags cleared).
    sci->SCIFFTX.all = 0xE040;
    sci->SCIFFRX.all = 0x2044;
    sci->SCIFFCT.all = 0x0000;

    // 8 data bits, idle-line, no parity, 1 stop. Loopback stays off.
    sci->SCICCR.all = 0x0007;
    // TX and RX enabled, SCI held in software reset.
    sci->SCICTL1.all = 0x0003;
    // Polling only: receiver and transmitter interrupts stay off.
    sci->SCICTL2.all = 0x0000;

    sci->SCIHBAUD.all = (Uint16)((SCIA_BRR >> 8) & 0x00FFU);
    sci->SCILBAUD.all = (Uint16)(SCIA_BRR & 0x00FFU);

    sci->SCICCR.bit.LOOPBKENA = 0;

    // Release software reset. TXENA and RXENA stay set.
    sci->SCICTL1.all = 0x0023;
}

//
// TX FIFO is 16 deep. A sample line is at most 10 bytes ("3723,3723\n")
// and takes about 0.87 ms at 115200 8N1, under the 2 ms tick. The FIFO
// therefore stays well below full. If it is full, spin until a slot
// opens so a byte is never dropped.
//
static void Sci_SendByte(volatile struct SCI_REGS *sci, Uint16 data)
{
    while(sci->SCIFFTX.bit.TXFFST >= 16U)
    {
    }

    sci->SCITXBUF.all = data & 0x00FFU;
}

static void SciA_SendString(const char *msg)
{
    while(*msg != 0)
    {
        Sci_SendByte(&SciaRegs, (Uint16)(*msg) & 0x00FFU);
        msg++;
    }
}

static void SciA_SendU16(Uint16 value)
{
    char buf[5];
    Uint16 n;

    n = 0U;
    do
    {
        buf[n] = (char)('0' + (value % 10U));
        n++;
        value = (Uint16)(value / 10U);
    }
    while((value != 0U) && (n < 5U));

    while(n > 0U)
    {
        n--;
        Sci_SendByte(&SciaRegs, (Uint16)buf[n]);
    }
}

static void SciA_Init(void)
{
    // SCIA on the LaunchPad XDS110 virtual COM port:
    //   GPIO28 mux 1 = SCIRXDA, asynchronous input, pull-up enabled
    //   GPIO29 mux 1 = SCITXDA
    // 115200 8N1, FIFO enabled, loopback off.
    EALLOW;
    GpioCtrlRegs.GPAGMUX2.bit.GPIO28 = 0;
    GpioCtrlRegs.GPAMUX2.bit.GPIO28 = 1;
    GpioCtrlRegs.GPAQSEL2.bit.GPIO28 = 3;
    GpioCtrlRegs.GPAPUD.bit.GPIO28 = 0;
    GpioCtrlRegs.GPADIR.bit.GPIO28 = 0;

    GpioCtrlRegs.GPAGMUX2.bit.GPIO29 = 0;
    GpioCtrlRegs.GPAMUX2.bit.GPIO29 = 1;
    GpioCtrlRegs.GPAPUD.bit.GPIO29 = 0;
    GpioCtrlRegs.GPADIR.bit.GPIO29 = 1;
    EDIS;

    Sci_Config(&SciaRegs);
}

static void AdcA_Init(void)
{
    // Internal 1.65 V reference, ADC full scale 3.3 V. See file header.
    SetVREF(ADC_ADCA, ADC_INTERNAL, ADC_VREF3P3);

    EALLOW;
    CpuSysRegs.PCLKCR13.bit.ADC_A = 1;
    // adc_ex1: PRESCALE 6 => ADCCLK = SYSCLK / 4 = 25 MHz.
    AdcaRegs.ADCCTL2.bit.PRESCALE = 6;
    // Late interrupt pulse: ADCINT1 is set when ADCRESULT0 is latched.
    AdcaRegs.ADCCTL1.bit.INTPULSEPOS = 1;
    AdcaRegs.ADCCTL1.bit.ADCPWDNZ = 1;
    EDIS;

    DELAY_US(1000);

    EALLOW;
    // Software trigger only. Channel A0 is the DACOUTA pin.
    AdcaRegs.ADCSOC0CTL.bit.CHSEL = 0;
    AdcaRegs.ADCSOC0CTL.bit.TRIGSEL = 0;
    AdcaRegs.ADCSOC0CTL.bit.ACQPS = 63;
    AdcaRegs.ADCINTSEL1N2.bit.INT1SEL = 0;
    AdcaRegs.ADCINTSEL1N2.bit.INT1E = 1;
    AdcaRegs.ADCINTSEL1N2.bit.INT1CONT = 0;
    AdcaRegs.ADCINTFLGCLR.bit.ADCINT1 = 1;
    AdcaRegs.ADCINTOVFCLR.bit.ADCINT1 = 1;
    EDIS;
}

static void DacA_Init(void)
{
    EALLOW;
    CpuSysRegs.PCLKCR16.bit.DAC_A = 1;
    // Load DACVALA from DACVALS on the next SYSCLK.
    DacaRegs.DACCTL.bit.LOADMODE = 0;
    // x2 gain so 1.65 V internal VREFHI becomes a 0-3.3 V output.
    DacaRegs.DACCTL.bit.MODE = 1;
    // Reference is ADC VREFHI, not the VDAC pin.
    DacaRegs.DACCTL.bit.DACREFSEL = 1;
    DacaRegs.DACOUTEN.bit.DACOUTEN = 1;
    DacaRegs.DACVALS.all = SINE_MID;
    EDIS;

    // dac_ex1 waits 10 us for the buffered DAC to power up.
    DELAY_US(10);
}

static void Timer0_Init(void)
{
    // Stop, /1 prescale, period 199999, free-run if the debugger halts.
    CpuTimer0Regs.TCR.bit.TSS = 1;
    CpuTimer0Regs.PRD.all = TIMER0_PRD;
    CpuTimer0Regs.TPR.all = 0;
    CpuTimer0Regs.TPRH.all = 0;
    // TSS=1, TRB=1, SOFT=1, FREE=1, TIE=0. Writing TIF=0 does not clear.
    CpuTimer0Regs.TCR.all = 0x0C30;
    // Write-1 clears TIF, then let the timer run.
    CpuTimer0Regs.TCR.bit.TIF = 1;
    CpuTimer0Regs.TCR.bit.TSS = 0;
}

static Uint16 AdcA_ReadA0(void)
{
    AdcaRegs.ADCSOCFRC1.bit.SOC0 = 1;

    while(AdcaRegs.ADCINTFLG.bit.ADCINT1 == 0U)
    {
    }

    AdcaRegs.ADCINTFLGCLR.bit.ADCINT1 = 1;
    if(AdcaRegs.ADCINTOVF.bit.ADCINT1 != 0U)
    {
        AdcaRegs.ADCINTOVFCLR.bit.ADCINT1 = 1;
        AdcaRegs.ADCINTFLGCLR.bit.ADCINT1 = 1;
    }

    return(AdcaResultRegs.ADCRESULT0);
}

static void Stream_SendSample(Uint16 dacCode, Uint16 adcCode)
{
    SciA_SendU16(dacCode);
    Sci_SendByte(&SciaRegs, (Uint16)',');
    SciA_SendU16(adcCode);
    Sci_SendByte(&SciaRegs, (Uint16)'\n');
}

void main(void)
{
    Uint16 index;
    Uint16 dacCode;
    Uint16 adcCode;

    InitSysCtrl();

    DINT;
    IER = 0x0000;
    IFR = 0x0000;

    AdcA_Init();
    DacA_Init();
    SciA_Init();
    Timer0_Init();

    // One legend line for the host plotter. No other text after this.
    SciA_SendString("dac,adc\n");

    index = 0U;

    for(;;)
    {
        while(CpuTimer0Regs.TCR.bit.TIF == 0U)
        {
        }
        CpuTimer0Regs.TCR.bit.TIF = 1;

        dacCode = sineTable[index];
        DacaRegs.DACVALS.all = dacCode;
        DELAY_US(20);
        adcCode = AdcA_ReadA0();
        Stream_SendSample(dacCode, adcCode);

        index++;
        if(index >= SINE_SAMPLES)
        {
            index = 0U;
        }
    }
}
