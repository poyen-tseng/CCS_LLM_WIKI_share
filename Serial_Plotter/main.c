// TITLE:  F280049C LaunchPad serial plotter
//
// DAC A drives a 256-step sine on DACOUTA. ADC A samples that same pin
// (ADCINA0) and SCIA streams "dac,adc" lines at 500 Hz. Polling only.
// Watchdog is disabled by codestart (WD_DISABLE) and again by InitSysCtrl().
//
//###########################################################################

#include "F28x_Project.h"

//
// SYSCLK = 10 MHz XTAL * IMULT_10 / PLLCLK_BY_2 = 100 MHz.
// InitSysCtrl() / InitPeripheralClocks() never write ClkCfgRegs.LOSPCP.
// LSPCLKDIV reset value is 2, which driverlib documents as
// SYSCTL_LSPCLK_PRESCALE_4 (default): LSPCLK = SYSCLK / 4 = 25 MHz.
// driverlib SysCtl_getLowSpeedClock() divides by (2 * LSPCLKDIV) when
// LSPCLKDIV != 0, which is the same /4.
//
// BRR = LSPCLK / (baud * 8) - 1
//     = 25000000 / (115200 * 8) - 1
//     = 27.1267... - 1
//     = 26.1267...
// Integer division truncates 25000000/921600 to 27, then subtracts 1,
// so the programmed BRR is 26 (0x001A). Same constant as the LaunchPad
// demo (SCIHBAUD = 0x00, SCILBAUD = 0x1A).
//
// Actual baud = 25000000 / ((26 + 1) * 8) = 115740.74 Hz
// Error = (115740.74 - 115200) / 115200 = +0.469%
//
#define SYSCLK_HZ            100000000UL
#define LSPCLK_DIV           4UL
#define LSPCLK_HZ            (SYSCLK_HZ / LSPCLK_DIV)
#define SCIA_BAUD_TARGET     115200UL
#define SCIA_BRR             ((LSPCLK_HZ / (SCIA_BAUD_TARGET * 8UL)) - 1UL)

#if (SCIA_BRR != 26)
#error "SCIA_BRR is not 26; check LSPCLK or the baud formula"
#endif

//
// CPU Timer0 counts SYSCLK. A period of (PRD + 1) cycles is exactly 2 ms
// when PRD = 100e6/500 - 1 = 199999. TIF is polled; the timer interrupt
// enable stays off.
//
#define SAMPLE_HZ            500UL
#define TIMER0_PRD           ((SYSCLK_HZ / SAMPLE_HZ) - 1UL)

#if (TIMER0_PRD != 199999UL)
#error "TIMER0_PRD is not 199999; sample period is not 2 ms"
#endif

#define SINE_SAMPLES         256U
#define SINE_MID             2048U

//
// Reference choice (0-3.3 V full scale on both ADC A and DAC A, no
// external reference and no jumper):
//
// 1. LaunchPad SPRUII7B section 2.1.8: VREFHIx is either driven externally
//    on header J15 or generated by the internal bandgap. J15 is optional,
//    so the internal bandgap is the no-parts path.
// 2. adc_ex1_soc_epwm.c calls
//    SetVREF(ADC_ADCA, ADC_INTERNAL, ADC_VREF3P3).
//    f28004x_adc_defines.h: ADC_INTERNAL=0, ADC_VREF3P3=0.
//    SetVREF writes ANAREFASEL=0 (internal) and ANAREFA2P5SEL=0, and the
//    function comment says that pair selects the "Internal / 1.65v mode"
//    offset trim. driverlib asysctl.h ASysCtl_setAnalogReference1P65()
//    clears the same ANAREFCTL bit (reference << 8). The ADC full-scale
//    name for that mode is 3.3 V (driverlib ADC_REFERENCE_3_3V = 0).
// 3. DACCTL.DACREFSEL = 1 selects the ADC VREFHI node, not the VDAC pin.
//    driverlib dac.h: DAC_REF_VDAC=0, DAC_REF_ADC_VREFHI=1.
//    dac_ex1_enable.c defaults to REFERENCE_VDAC and says an external
//    3.3 V wire must be tied to ADCINB3/VDAC. That path is not used here.
// 4. With DACREFSEL=1 and the ADC internal reference, DACCTL.MODE is the
//    buffer gain. driverlib dac.h: DAC_GAIN_ONE=0, DAC_GAIN_TWO=2.
//    DAC_CTL_MODE is 0x2, so the bitfield MODE=1 is the x2 gain.
//    The same header notes that MODE is used only for the internal
//    VREFHI reference. x2 turns the 1.65 V internal reference into a
//    0-3.3 V DAC span, which matches the ADC 3.3 V full scale.
//    GPIO_EX1 Init_DAC uses this same MODE=1 / DACREFSEL=1 pair.
// 5. ADCINA0 and DACOUTA are the same pin (dac_ex1: "DACOUTA/ADCINA0").
//    No GPIO mux and no board wire.
//
// ADCCLK: adc_ex1 sets ADCCTL2.PRESCALE = 6 and comments "divider to /4".
// driverlib ADC_CLK_DIV_4_0 = 6. At SYSCLK = 100 MHz, ADCCLK = 25 MHz.
//
// ACQPS = 63 -> sample window (63 + 1) SYSCLK = 640 ns, long enough for
// the buffered DAC output impedance on the shared pin.
//

